export const DEFAULT_TERMINAL_SCHEME_ID = "builtin:graphite-dark";
export const DEFAULT_LIGHT_TERMINAL_SCHEME_ID = "builtin:graphite-light";

export function getBuiltinTerminalScheme(id: string) {
  return BUILTIN_TERMINAL_SCHEMES.find((scheme) => scheme.id === id) ?? null;
}

export function getBuiltinTerminalColors(): TerminalColors {
  return structuredClone(BUILTIN_TERMINAL_SCHEMES[0].colors);
}
